VOLUME_NUMBER_BY_OPENING = {
    "雪城坠海": 1,
    "锚位拍卖": 2,
    "镜潮倒城": 3,
    "群栖来客": 4,
    "五契同撤": 5,
    "各界署名": 6,
}


def build() -> list[dict[str, object]]:
    root = Path(__file__).resolve().parent
    core = json.loads((root / "core.json").read_text(encoding="utf-8"))
    character_ids = {item["character_id"] for item in core["characters"]}
    thread_ids = {item["thread_id"] for item in core["plot_threads"]}
    event_chapters = {
        item["event_id"]: item["chapter_no"] for item in core["event_graph"]["nodes"]
    }
    ordered = sorted(VOLUMES, key=lambda rows: VOLUME_NUMBER_BY_OPENING[rows[0].title])
    assert len(ordered) == 6, f"expected 6 volumes, got {len(ordered)}"
    assert all(len(rows) == 16 for rows in ordered), [len(rows) for rows in ordered]
    assert {rows[0].title for rows in ordered} == set(VOLUME_NUMBER_BY_OPENING)

    chapters: list[dict[str, object]] = []
    seen_titles: set[str] = set()
    for volume_no, rows in enumerate(ordered, start=1):
        assert VOLUME_NUMBER_BY_OPENING[rows[0].title] == volume_no
        for row in rows:
            chapter_no = len(chapters) + 1
            assert row.title not in seen_titles, f"duplicate title: {row.title}"
            seen_titles.add(row.title)
            assert row.driver in character_ids and row.driver in row.characters, row.title
            assert set(row.characters) <= character_ids, row.title
            assert row.events and set(row.events) <= set(event_chapters), row.title
            assert row.threads and set(row.threads) <= thread_ids, row.title
            assert all(
                isinstance(value, str) and value.strip()
                for value in (
                    row.title,
                    row.goal,
                    row.opposition,
                    row.turn,
                    row.cost,
                    row.payoff,
                    row.question,
                )
            ), row.title
            dependencies = sorted(
                ({chapter_no - 1} if chapter_no > 1 else set())
                | set(row.extra_dependencies)
            )
            assert all(0 < item < chapter_no for item in dependencies), row.title
            forbidden = [
                "不得以巧合、临时新增能力或未登记的外援无代价解决本章冲突",
                "不得替未在场者作出永久签署、撤回或身体关系决定",
                "不得用解释性总结代替人物行动、选择和可观察的状态变化",
            ]
            if REL in row.threads:
                forbidden.append("不得把沉默、服从、受困或权力差解释为同意")
            else:
                forbidden.append("不得在章末把信息、关系、资源与可用选择全部恢复到章初")
            chapters.append(
                {
                    "chapter_no": chapter_no,
                    "volume_no": volume_no,
                    "title": row.title,
                    "active_driver": row.driver,
                    "involved_character_ids": list(row.characters),
                    "goal": row.goal,
                    "opposition": row.opposition,
                    "turn": row.turn,
                    "cost": row.cost,
                    "payoff": row.payoff,
                    "new_question": row.question,
                    "event_ids": list(row.events),
                    "plot_thread_ids": list(row.threads),
                    "depends_on_chapters": dependencies,
                    "forbidden_outcomes": forbidden,
                }
            )

    assert len(chapters) == core["book"]["target_chapters"] == 96
    for event_id, chapter_no in event_chapters.items():
        assert event_id in chapters[chapter_no - 1]["event_ids"], (
            event_id,
            chapter_no,
            chapters[chapter_no - 1]["title"],
        )
    return chapters


def main() -> None:
    destination = Path(__file__).resolve().with_name("chapters.json")
    destination.write_text(
        json.dumps(build(), ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    print(f"wrote {destination} with 96 chapter contracts")


